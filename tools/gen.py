#!/usr/bin/env python3
"""Generate everything the book computes from data/.

Single sources of truth: data/chapters.tsv (the sequence) and the book's own tables
(speeds.tsv, lengths.tsv: arytmetyka czytania).
Written to generated/ (COMMITTED, so a changed number shows in review and CI fails on drift):
  generated/structure.tex   \\part / \\input sequence for main.tex
  generated/meta.tex        chapter titles and lead lines as \\csdef macros
  generated/values.tex      every count the book prints, as \\gval keys
  generated/books-per-year.tex, book-lengths.tex  tablice liczone z prędkości i długości książek
Usage: python3 tools/gen.py [--check]   Stdlib only.
"""
import re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GEN = ROOT / "generated"
CHECK = "--check" in sys.argv
PARTIAL = "--partial" in sys.argv
SPECIAL = {"&": r"\&", "%": r"\%", "#": r"\#", "_": r"\_", "$": r"\$"}

def tex(s):
    return "".join(SPECIAL.get(c, c) for c in s).replace("~", r"\textasciitilde{}")

def read_tsv(name):
    lines = (ROOT / "data" / name).read_text(encoding="utf-8").splitlines()
    return [ln.split("\t") for ln in lines[1:] if ln.strip() and not ln.startswith("#")]

def ascii_key(s):
    return s.translate(str.maketrans("ąćęłńóśźż","acelnoszz"))

def fmt(x, nd=1):
    s = f"{x:.{nd}f}".replace(".", ",")
    return s.rstrip("0").rstrip(",") if "," in s else s

out = {}
chapters = read_tsv("chapters.tsv")
written = {p.name for p in (ROOT / "chapters").glob("c*.tex")}
vals = {}

# ---- structure and meta ---------------------------------------------------
st, meta, part = [], [], None
for n, short, partname, slug, lead in chapters:
    nn = f"{int(n):02d}"
    fn = f"c{nn}-{slug}"
    meta.append(f"\\csgdef{{chtitle@{nn}}}{{{tex(short)}}}\n\\csgdef{{chlead@{nn}}}{{{tex(lead)}}}")
    if partname != part:
        st.append(f"\\part{{{tex(partname)}}}"); part = partname
    if f"{fn}.tex" in written or not PARTIAL:
        st.append(f"\\input{{chapters/{fn}}}")
out["structure.tex"] = "% GENERATED by tools/gen.py -- do not edit\n" + "\n".join(st) + "\n"
out["meta.tex"] = "% GENERATED by tools/gen.py -- do not edit\n" + "\n".join(meta) + "\n"

# ---- counts from the sources ---------------------------------------------
def strip_comments(s): return re.sub(r"(?<!\\)%.*", "", s)
ex = tasks = traps = verify = 0
wr = 0
for p in sorted((ROOT / "chapters").glob("c*.tex")):
    s = strip_comments(p.read_text(encoding="utf-8"))
    wr += 1
    ex += len(re.findall(r"\\exitem\{", s)); tasks += len(re.findall(r"\\zadanie\{", s))
    traps += len(re.findall(r"\\begin\{falle\}", s)); verify += len(re.findall(r"\\verify\{", s))
for sub in ("frontmatter", "appendices"):
    for p in sorted((ROOT / sub).glob("*.tex")):
        verify += len(re.findall(r"\\verify\{", strip_comments(p.read_text(encoding="utf-8"))))
vals.update({"chapters.total": len(chapters), "written.total": wr, "exercises.total": ex,
             "tasks.total": tasks, "traps.total": traps, "verify.total": verify})

# ---- reading arithmetic: books per year = minutes/day * 365 * wpm / words ---
speeds = [int(r[0]) for r in read_tsv("speeds.tsv")]
lengths = [(r[0], int(r[1])) for r in read_tsv("lengths.tsv")]
minutes = [10, 20, 30, 45, 60, 90]
typ = dict(lengths)["typowa"]
body = ["\\begin{center}\\small\\begin{tabular}{@{}r" + "r" * len(speeds) + "@{}}\\toprule",
        "\\textsf{\\textbf{min/dzień}}" + "".join(f"&\\textsf{{\\textbf{{{s} sł./min}}}}" for s in speeds) + "\\\\\\midrule"]
for m in minutes:
    cells = []
    for s in speeds:
        b = m * 365 * s / typ
        vals[f"books.{m}.{s}"] = fmt(b, 1); cells.append(fmt(b, 1))
    body.append(f"{m}&" + "&".join(cells) + "\\\\")
body.append("\\bottomrule\\end{tabular}\\end{center}")
out["books-per-year.tex"] = "% GENERATED by tools/gen.py -- do not edit\n" + "\n".join(body) + "\n"
body = ["\\begin{center}\\small\\begin{tabular}{@{}lrr@{}}\\toprule\\textsf{\\textbf{Rodzaj książki}}&\\textsf{\\textbf{słów}}&\\textsf{\\textbf{godzin przy 250 sł./min}}\\\\\\midrule"]
for name, w in lengths:
    h = w / 250 / 60
    vals[f"len.{ascii_key(name)}.hours"] = fmt(h, 1); body.append(f"{tex(name)}&{w}&{fmt(h,1)}\\\\")
body.append("\\bottomrule\\end{tabular}\\end{center}")
out["book-lengths.tex"] = "% GENERATED by tools/gen.py -- do not edit\n" + "\n".join(body) + "\n"
# minutes needed per day for N books a year (typical book, 250 wpm)
for n in (12, 24, 52):
    vals[f"need.{n}"] = fmt(n * typ / 250 / 365, 1)
vals["typical.words"] = typ
vals["typical.hours"] = fmt(typ / 250 / 60, 1)


out["values.tex"] = "% GENERATED by tools/gen.py -- do not edit\n" + "\n".join(
    f"\\csgdef{{gval@{k}}}{{{v}}}" for k, v in sorted(vals.items())) + "\n"

stale = []
GEN.mkdir(exist_ok=True)
for name, text in out.items():
    p = GEN / name
    if CHECK:
        if not p.exists() or p.read_text(encoding="utf-8") != text: stale.append(name)
    else:
        p.write_text(text, encoding="utf-8")
if CHECK:
    if stale:
        print("STALE: " + ", ".join(stale) + "  -- run python3 tools/gen.py and commit"); sys.exit(1)
    print(f"gen --check: {len(out)} generated files current")
else:
    print(f"gen: wrote {len(out)} files")
